pub const ExpressionId = enum(u32) { _ };
pub const Block = struct { start: u32 = 0, len: u32 = 0 };

pub const Expression = union(enum) {
    identifier: []const u8,
    null_value,
    unit,
    return_value: ?ExpressionId,
    catch_scope: struct { value: ExpressionId, capture: ?[]const u8 = null, body: Block },
    fixed_array_type: struct { length: ExpressionId, element: ExpressionId },
    undefined_value,
    unreachable_value,
    optional_type: ExpressionId,
    tuple_type: []const ExpressionId,
    enum_type: []const []const u8,
    enum_literal: []const u8,
    array: struct { element_type: ExpressionId, values: []const ExpressionId },
    tuple: []const ExpressionId,
    index: struct { target: ExpressionId, index: ExpressionId },
    slice: struct { target: ExpressionId, start: ?ExpressionId = null, end: ?ExpressionId = null },
    range: struct { start: ExpressionId, end: ExpressionId },
    address_of: ExpressionId,
    error_value: []const u8,
    block: struct { label: []const u8, statements: Block },
    try_value: ExpressionId,
    catch_value: struct { value: ExpressionId, capture: []const u8, label: []const u8, result: ExpressionId },
    comptime_value: ExpressionId,
    error_set: []const []const u8,
    error_union: struct { payload: ExpressionId, errors: ?[]const []const u8 = null, inferred: bool = false },
    integer: u64,
    float: f64,
    string: []const u8,
    boolean: bool,
    primitive: enum { @"anytype", type, anyerror, anyopaque, void, bool, u8, u16, u32, u64, usize, i32, i33, i64, i65, f32, f64 },
    dereference: ExpressionId,
    optional_unwrap: ExpressionId,
    selection: struct { subject: ExpressionId, arms: []const SelectionArm },
    pointer: ExpressionId,
    const_pointer: ExpressionId,
    const_slice: ExpressionId,
    mutable_slice: ExpressionId,
    many_pointer: ExpressionId,
    opaque_type,
    struct_type: []const Field,
    namespace_type: []const Declaration,
    container_type: struct { fields: []const Field, declarations: []const Declaration },
    field: struct { target: ExpressionId, name: []const u8 },
    unary: struct { operator: enum { negate, not }, operand: ExpressionId },
    binary: struct { operator: BinaryOperator, left: ExpressionId, right: ExpressionId },
    builtin: struct { name: enum { divTrunc, rem, as, setRuntimeSafety, import, embedFile, intCast, floatCast, floatFromInt, intFromFloat, trunc, tagName, enumFromInt, intFromEnum, TypeOf, FieldType, typeInfo, sizeOf, max, intFromPtr, Int, @"export", compileError, intFromBool, errorName, This, constCast, ptrCast, alignCast, memcpy, Vector, splat }, arguments: []const ExpressionId },
    call: struct { callee: ExpressionId, arguments: []const ExpressionId },
    conditional: struct { condition: ExpressionId, yes: ExpressionId, no: ExpressionId, capture: ?[]const u8 = null, error_capture: ?[]const u8 = null },
    object: struct { type_expr: ?ExpressionId = null, fields: []const Field },
};

pub const BinaryOperator = enum {
    add,
    saturating_add,
    shift_left,
    subtract,
    multiply,
    divide,
    equal,
    not_equal,
    less,
    less_equal,
    greater,
    greater_equal,
    logical_and,
    logical_or,
    coalesce,
    pub fn spelling(self: BinaryOperator) []const u8 {
        return switch (self) {
            .add => "+",
            .saturating_add => "+|",
            .shift_left => "<<",
            .subtract => "-",
            .multiply => "*",
            .divide => "/",
            .equal => "==",
            .not_equal => "!=",
            .less => "<",
            .less_equal => "<=",
            .greater => ">",
            .greater_equal => ">=",
            .logical_and => "and",
            .logical_or => "or",
            .coalesce => "orelse",
        };
    }
};

pub const SelectionArm = struct { value: ?ExpressionId = null, capture: ?[]const u8 = null, result: ExpressionId };
pub const Field = struct { name: []const u8, value: ExpressionId, default_value: ?ExpressionId = null, comptime_parameter: bool = false };
pub const Constant = struct { name: []const u8, type_expr: ?ExpressionId = null, value: ExpressionId, exported: bool = false };

pub const Statement = union(enum) {
    scope: Block,
    defer_expression: ExpressionId,
    errdefer_expression: ExpressionId,
    defer_scope: Block,
    discard_error: ExpressionId,
    constant: Constant,
    variable: Constant,
    assignment: struct { target: ExpressionId, value: ExpressionId },
    for_loop: struct { iterable: ExpressionId, capture: []const u8, body: Block, capture_reference: bool = false, index_capture: ?[]const u8 = null },
    while_loop: struct { condition: ExpressionId, body: Block, capture: ?[]const u8 = null },
    break_loop,
    continue_loop,
    break_value: struct { label: []const u8, value: ExpressionId },
    unreachable_stmt,
    result: ?ExpressionId,
    branch: struct { condition: ExpressionId, yes: Block, no: Block, capture: ?[]const u8 = null, capture_reference: bool = false, error_capture: ?[]const u8 = null },
    discard: ExpressionId,
    expression: ExpressionId,
};

pub const Function = struct {
    name: []const u8,
    parameters: []const Field,
    return_type: ExpressionId,
    body: Block,
    exported: bool = false,
    abi_export: bool = false,
    inlined: bool = false,
    calling_convention: ?ExpressionId = null,
};

pub const Declaration = union(enum) { constant: Constant, variable: Constant, function: Function, field: Field, comptime_scope: Block };
