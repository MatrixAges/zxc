const cases: Array<Case> = []

for (const [range, expected] of expectations) {
	if (expected.length !== versions.length || !/^[01]+$/.test(expected)) throw new Error('invalid semver expectation vector')

	for (const [index, version] of versions.entries()) {
		cases.push({
			name: `range ${JSON.stringify(range)} / ${version}`,
			root: { dependencies: { a: `workspace:${range}` } },
			members: { 'pkgs/a': { name: 'a', version } },
			...(expected[index] === '1'
				? { edges: [['root', 'a', 'a', false]] as Array<[string, string, string, boolean]> }
				: { diagnostic: './pkg.yaml: dependency a: workspace package version does not satisfy the dependency range\n' }),
		})
	}
}

for (const range of ['1..2', '01.2.3', '1.02.3', '1.2.03', '1.2.3.4', 'x.2', '1.x.3', '1.2-alpha', '1.2.3-', '1.2.3+', '!=1.2.3', '==1.2.3', '><1.2.3', '>=', '1.2.3 -', '1.2.3 - 2.0.0 extra', '1.2.3 || nope', 'nope || 1.2.3']) {
	cases.push({
		name: `invalid range ${range}`,
		root: { dependencies: { a: `workspace:${range}` } },
		members: { 'pkgs/a': { name: 'a', version: '1.2.3' } },
		diagnostic: './pkg.yaml: dependency a: invalid workspace version range\n',
	})
}

for (const range of ['*', '^', '~']) {
	for (const version of ['0.0.0', '1.2.3-alpha', '2.0.0+build']) {
		cases.push({
			name: `workspace shortcut ${range} / ${version}`,
			root: { dependencies: { a: `workspace:${range}` } },
			members: { 'pkgs/a': { name: 'a', version } },
			edges: [['root', 'a', 'a', false]],
		})
	}
}

export default cases
