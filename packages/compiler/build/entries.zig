pub fn of(set: Set) []const Entry {
    return switch (set) {
        .main => &main,
        .checks => &checks,
        .ordered => &ordered,
        .collections => &collections,
        .growth => &growth,
        .host => &host,
        .constant_seed => &.{constant_fold},
        .snapshot_seed => &.{input_snapshot},
        .partition_seed => &.{partition_groups},
    };
}

pub const ModuleEntry = struct {
    set: Set,
    entry: Entry,
    file: []const u8,
    import_name: []const u8,
};

pub const module_entries = block: {
    @setEvalBranchQuota(10_000);

    const sets = .{ Set.main, Set.ordered, Set.collections, Set.growth, Set.host };
    var count: usize = 0;

    for (sets) |set| {
        for (if (set == .host) &host_bindings else of(set)) |entry| {
            if (entry.owner != .lint) count += 1;
        }
    }

    var result: [count]ModuleEntry = undefined;
    var index: usize = 0;

    for (sets) |set| {
        for (if (set == .host) &host_bindings else of(set)) |entry| {
            if (entry.owner == .lint) continue;

            result[index] = .{ .set = set, .entry = entry, .file = entry.name ++ ".zig", .import_name = entry.importName() };
            index += 1;
        }
    }

    break :block result;
};
