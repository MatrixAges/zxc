const std = @import("std");
const hash = @import("hash.zig");
const kdf = @import("kdf.zig");
const aead = @import("aead.zig");
const Sha256 = kdf.Module(std.crypto.auth.hmac.sha2.HmacSha256);
const Sha512 = kdf.Module(std.crypto.auth.hmac.sha2.HmacSha512);
const Aes128 = aead.Module(std.crypto.aead.aes_gcm.Aes128Gcm, (1 << 36) - 32);
const Aes256 = aead.Module(std.crypto.aead.aes_gcm.Aes256Gcm, (1 << 36) - 32);
const ChaCha = aead.Module(std.crypto.aead.chacha_poly.ChaCha20Poly1305, (1 << 38) - 64);
pub const sha256 = hash.sha256;
pub const sha512 = hash.sha512;
pub const hmacSha256 = Sha256.hmac;
pub const hmacSha512 = Sha512.hmac;
pub const verifyHmacSha256 = Sha256.verifyHmac;
pub const verifyHmacSha512 = Sha512.verifyHmac;
pub const timingSafeEqual = @import("compare.zig").timingSafeEqual;
pub const hkdfSha256 = Sha256.hkdf;
pub const hkdfSha512 = Sha512.hkdf;
pub const pbkdf2Sha256 = Sha256.pbkdf2;
pub const pbkdf2Sha512 = Sha512.pbkdf2;
pub const encryptAes128Gcm = Aes128.encrypt;
pub const decryptAes128Gcm = Aes128.decrypt;
pub const encryptAes256Gcm = Aes256.encrypt;
pub const decryptAes256Gcm = Aes256.decrypt;
pub const encryptChaCha20Poly1305 = ChaCha.encrypt;
pub const decryptChaCha20Poly1305 = ChaCha.decrypt;
pub const scrypt = @import("scrypt.zig").scrypt;
